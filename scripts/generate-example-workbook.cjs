const fs = require("fs");
const path = require("path");
const XLSX = require("../importer-desktop/node_modules/xlsx");
const root = path.resolve(__dirname, "..");
const dataDir = path.join(root, "kit-free", "datos-ejemplo");
const peoplePath = path.join(dataDir, "personas.csv");
const parse = (file) => { const [head, ...lines] = fs.readFileSync(file, "utf8").replace(/^\uFEFF/, "").trim().split(/\r?\n/); const headers = head.split(","); return lines.map((line) => Object.fromEntries(headers.map((key, index) => [key, line.split(",")[index] ?? ""]))); };
const people = parse(peoplePath);
const education = ["FP", "Grado", "Máster", "Bachillerato"];
const marital = ["Soltero/a", "Casado/a", "Pareja de hecho"];
const work = ["Híbrido", "Presencial", "Remoto"];
const contract = ["Indefinido", "Indefinido", "Indefinido", "Temporal"];
const level = ["Junior", "Profesional", "Senior", "Manager"];
for (const [index, person] of people.entries()) Object.assign(person, { NivelEducativo: education[index % education.length], EstadoCivil: marital[index % marital.length], NumeroHijos: String(index % 4), ModalidadTrabajo: work[index % work.length], TipoContrato: contract[index % contract.length], NivelPuesto: level[index % level.length] });
const headers = Object.keys(people[0]);
fs.writeFileSync(peoplePath, `\uFEFF${[headers.join(","), ...people.map((row) => headers.map((header) => row[header]).join(","))].join("\r\n")}`, "utf8");
const leaves = parse(path.join(dataDir, "bajas_medicas.csv"));
const workbook = XLSX.utils.book_new();
XLSX.utils.book_append_sheet(workbook, XLSX.utils.json_to_sheet(people), "Personas");
XLSX.utils.book_append_sheet(workbook, XLSX.utils.json_to_sheet(leaves), "BajasMedicas");
XLSX.writeFile(workbook, path.join(dataDir, "plantilla-demografica-ejemplo.xlsx"));
